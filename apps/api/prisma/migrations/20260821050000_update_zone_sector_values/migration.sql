-- Sector: ALIMENTOS_Y_BEBIDAS -> ALIMENTOS_RESTAURANTES
--         ABARROTES_Y_TIENDA -> TIENDAS_VIVERES
--         ROPA_Y_CALZADO -> CONFECCION_COSTURA
