--         TRANSPORTE -> TRANSPORTE_MENSAJERIA
--         SERVICIOS_PROFESIONALES -> OTRO
--         ARTE_Y_ARTESANIAS -> DISENO_ARTE
--         AGROPECUARIO -> JARDINERIA_AGRO
--         OTRO -> OTRO

-- ---------------------------------------------------------------------------
-- Zone
-- ---------------------------------------------------------------------------
CREATE TYPE "Zone_new" AS ENUM (
  'ATARDECERES',
  'CIUDADELA_DEL_NORTE',
  'CUMANDAY',
  'ECOTURISTICO_CERRO_DE_ORO',
  'LA_ESTACION',
  'LA_ESTRELLA',
  'LA_FUENTE',
  'LA_MACARENA',
  'NUEVO_HORIZONTE',
  'PALOGRANDE',
  'SAN_JOSE',
  'TESORITO',
  'UNIVERSITARIA',
  'RURAL_ALEDANA'
);

ALTER TABLE "Business" ALTER COLUMN "zone" TYPE "Zone_new" USING (
  CASE "zone"::text
    WHEN 'ESTACION' THEN 'LA_ESTACION'
    WHEN 'OTRA' THEN 'RURAL_ALEDANA'
    ELSE "zone"::text
  END
)::"Zone_new";

ALTER TABLE "SupportPost" ALTER COLUMN "zone" TYPE "Zone_new" USING (
  CASE "zone"::text
    WHEN 'ESTACION' THEN 'LA_ESTACION'
    WHEN 'OTRA' THEN 'RURAL_ALEDANA'
    ELSE "zone"::text
  END
)::"Zone_new";

DROP TYPE "Zone";
ALTER TYPE "Zone_new" RENAME TO "Zone";

